// Builds what the Claude Code plugin ships: `npm run bundle`.
// - skills/agent-trap-scan/scripts/agent-trap-scan.mjs: the scanner as one file, no dependencies beyond Node
// - hooks/hooks.json: the hook configuration that runs it
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { build } from "esbuild";
import { AGENT_CONFIG_FILE_PATHS, AGENT_DIR_NAMES, AGENT_FILE_NAMES, GITHUB_AGENT_DIR_NAMES, SHALLOW_AGENT_FILE_NAMES } from "../src/surface.ts";
import { VERSION } from "../src/version.ts";

const root = join(import.meta.dirname, "..");
const outfile = join(root, "skills", "agent-trap-scan", "scripts", "agent-trap-scan.mjs");

await build({
  entryPoints: [join(root, "src", "cli.ts")],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  legalComments: "none",
  banner: { js: `// agent-trap-scan ${VERSION}: generated by \`npm run bundle\` from src/. Do not edit.` },
});
console.log(`wrote ${outfile}`);

// Shell form, so it also runs on Claude Code versions without exec-form hooks.
const command = 'node "${CLAUDE_PLUGIN_ROOT}/skills/agent-trap-scan/scripts/agent-trap-scan.mjs" hook';

// Each `if` filter keeps Node from starting on every Read or shell command; the script checks again.
// `//**/` anchors at the filesystem root, so files outside the working directory (fresh clones) match too.
// The lists come from src/surface.ts, so the hooks fire for every file the scanner classifies.
const both = (name: string) => [...new Set([name, name.toLowerCase()])];
const NAMES = [...AGENT_FILE_NAMES, ...SHALLOW_AGENT_FILE_NAMES].flatMap(both);
const OTHER_FILES = ["CONTRIBUTING*", "contributing*", "AI_POLICY*", "AI-POLICY*", "ai_policy*", "ai-policy*", "SECURITY.md", "README*", "readme*"];
const TEMPLATES = ["*_TEMPLATE*", "*_template*", "ISSUE_TEMPLATE/**", "PULL_REQUEST_TEMPLATE/**", "issue_template/**", "merge_request_templates/**", "issue_templates/**"];
const DIRS = [...AGENT_DIR_NAMES.map((d) => `${d}/**`), ...GITHUB_AGENT_DIR_NAMES.map((d) => `.github/${d}/**`)];
const READ_PATTERNS = [...new Set([...NAMES, ...OTHER_FILES, ...TEMPLATES, ...DIRS, ...AGENT_CONFIG_FILE_PATHS])];
const SHELL_PATTERNS = [
  "git clone *",
  "git -C * clone *",
  "gh repo clone *",
  ...new Set([...NAMES.map((n) => `*${n}*`), "*CONTRIBUTING*", "*contributing*", "*PULL_REQUEST_TEMPLATE*", "*pull_request_template*"]),
];

const handler = (filter: string, timeout: number, statusMessage?: string) => ({
  type: "command",
  if: filter,
  command,
  timeout,
  ...(statusMessage ? { statusMessage } : {}),
});

const hooks = {
  description: "agent-trap-scan: flag risky text aimed at AI agents in repositories you open, clone or read",
  hooks: {
    SessionStart: [
      {
        matcher: "startup|resume|clear|compact|fork",
        hooks: [{ type: "command", command, timeout: 30, statusMessage: "Scanning this repository for agent traps" }],
      },
    ],
    PreToolUse: [{ matcher: "Read", hooks: READ_PATTERNS.map((p) => handler(`Read(//**/${p})`, 10)) }],
    PostToolUse: [
      { matcher: "Bash", hooks: SHELL_PATTERNS.map((p) => handler(`Bash(${p})`, 30, "Scanning for agent traps")) },
      { matcher: "PowerShell", hooks: SHELL_PATTERNS.map((p) => handler(`PowerShell(${p})`, 30, "Scanning for agent traps")) },
    ],
  },
};
await writeFile(join(root, "hooks", "hooks.json"), `${JSON.stringify(hooks, null, 2)}\n`);
console.log("wrote hooks/hooks.json");
